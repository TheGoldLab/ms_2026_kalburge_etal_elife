"""
Data loading, processing, and summary-statistics utilities for the Pigeon project.
Python translations of the MATLAB getPigeon_* functions.

Main pipeline
-------------
1. ``get_data_table``        — reads per-subject CSV files, calls
   ``get_bounds`` on the resulting step sequences, optionally merges the
   six task blocks into three, and applies ``apply_bias_corrections``.
2. ``get_bounds``            — from raw step sequences infers the bound
   (decision threshold position at the time of choice), DT (steps after
   NDT), RT (total steps), and the congruence array (fraction of trials
   where the pigeon's position at each NDT lag aligns with the final choice).
3. ``get_good_trial_array``  — returns a boolean mask implementing the
   standard quality filter: DT ≥ 2, trial_number ≥ 10, wall_hit = False.
4. ``apply_bias_corrections`` — applies per-(DT, SNR-bin) linear correction
   to the inferred bound using coefficients from a .mat file generated by
   ``notebooks/Make_biasCorrection.ipynb``.
5. ``get_performance_summary`` / ``get_bound_summary`` — per-subject/block/SNR
   accuracy, DT, and |bound| statistics over an already-built data table.
   Both apply ``get_good_trial_array`` internally by default.
6. ``get_bound_summaries_wcp`` — change-point-specific composed summary
   (LowHigh/HighLow/Low/High/CP* struct), built on top of ``get_bound_summary``,
   translated from ``getBoundSummarieswCP.m``. Usage:

       from pigeon.data import get_data_table, get_bound_summaries_wcp
       from pigeon.pathDefaults import BIAS_CORRECTION_CP_FILE

       data_table_mxsc = get_data_table(
           task_type="MXSC",
           combine_snr=False, correct_bias=BIAS_CORRECTION_CP_FILE,
       )
       bound_summaries = get_bound_summaries_wcp(data_table_mxsc)

   CP calibration files must match the data's task design:
   ``get_cp_generative_params`` reads the generative step mean/SD from the
   data, ``get_data_table`` checks the CP bias-correction file's SNRs
   against it, and ``load_cp_rr_mats`` checks RRMats.mat's ``g_means`` /
   ``g_std`` / CP steps before returning it.

   Called directly (no caching layer) by ``notebooks/Figure06_cpSummary.ipynb``,
   ``notebooks/Make_RRMatrix.ipynb``, and ``notebooks/Test_cpData.ipynb`` --
   this call is fast (seconds), so all three just recompute it rather than
   reading a pre-saved .mat file.

Key constants
-------------
RAW_DATA_DIR : Path
    Default path to the top-level raw CSV data directory (from pathDefaults).
WALL : float
    Screen-edge limit (0.75).  Trials where any step position reaches this
    limit are flagged ``wall_hit = True`` and excluded by
    ``get_good_trial_array``.
"""

from __future__ import annotations

import os
import glob
from dataclasses import dataclass
from typing import Any, Mapping

import numpy as np
import pandas as pd
import scipy.io


from .pathDefaults import RAW_DATA_DIR, BIAS_CORRECTION_FILE, MXSC_CP_METHOD_FILE

WALL = 0.75  # screen-edge limit; trials where any step position reaches |WALL| are flagged wall_hit = True


def _load_mxsc_cp_methods(path=MXSC_CP_METHOD_FILE):
    """Read the per-subject CP-time method manifest for the MXSC task.

    Parameters
    ----------
    path : str or Path
        Path to the manifest (``<method><tab><csv filename>`` per line,
        ``#``-prefixed comment lines and blank lines ignored).

    Returns
    -------
    dict[str, str]
        Maps CSV basename -> 'mean' or 'median'.
    """
    methods = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            method, fname = line.split("\t")
            methods[fname] = method
    return methods

def get_data_table(task_type="MX", data_dir=RAW_DATA_DIR, blocks="all",
                   combine_snr=True, correct_bias=BIAS_CORRECTION_FILE,
                   max_ndt=5, peak_step_bound=True,
                   exclude_switched_trials_from_ndt=False):
    """
    Load and return a DataFrame of trial data.
    Translated from getPigeon_dataTable.m

    Parameters
    ----------
    task_type : str
        'OL' (blocked SNR), 'MX' (mixed SNR), 'PD' (predefined bound), or
        'MXSC' (mixed SNR with change-point blocks). Any task_type containing
        'MX' (e.g. 'MX', 'MXSC') is treated as an online mixed-SNR task for
        column selection and bound computation; any task_type containing 'SC'
        (e.g. 'MXSC') additionally gets a per-trial change_point column
        computed from canonical blocks 1/2 (pre-change) and 3/4 (post-change).
        Two MXSC conditions-file layouts have been used across data
        collection: a legacy 5-block layout (1/2 fixed, 3 an unused mixed-SNR
        block, 4/5 the change-point blocks) and the current 4-block layout
        (1/2 fixed, 3/4 the change-point blocks, block 3 of the old layout
        removed). block_index is remapped onto the current numbering for
        legacy files (detected by the absence of a switch_time column) so
        both eras share one canonical block_index -- see the remapping note
        where block_index is built, below.
        The 'CP' (change-point) task is not yet implemented in Python;
        use the MATLAB pipeline to generate pre-computed summaries.
        'PD' (predefined bound): the subject chooses the bound before the
        trial starts, so there's no step-position bound estimation, no NDT,
        and no bias correction (correct_bias is ignored for 'PD' -- see
        below). bound is `predefined_bound` signed by choice direction
        (right = +), and DT = RT (every step is deliberation time; no NDT
        to subtract).
    data_dir : str
        Path to the data directory
    blocks : str or list
        'all' or list of block numbers to include
    combine_snr : bool
        If True, combine 6 blocks into 3 (blocked/mixed SNR logic)
    correct_bias : str or None
        Path to .mat bias correction file, or None to skip. Ignored for
        task_type='PD' (see task_type above): its bound has no measurement
        bias to correct.
    max_ndt : int
        Max NDT lag to consider when building the bound matrix (see get_bounds).
    peak_step_bound : bool
        If True (default), apply the peak-step bound correction (a Python-only
        enhancement not present in getPigeon_bounds.m) -- see get_bounds.
    exclude_switched_trials_from_ndt : bool
        MXSC ('SC' in task_type) only; no effect otherwise. If True, the
        lowest-SNR trial pool get_bounds' NDT search draws on (see get_bounds'
        `change_point` parameter) excludes changepoint trials whose RT
        exceeds their own change_point -- these are labeled with their
        pre-switch snr but actually ran into the noisier, bigger-step
        post-switch regime before the response, which dilutes/biases the
        congruence curve the NDT search relies on. Default False (matches
        prior behavior, and every non-MXSC caller) -- see
        notebooks/Test_NDT.ipynb for the contamination this addresses and
        notebooks/Figure06_cpSummary.ipynb for its effect on the CP results.

    Returns
    -------
    pd.DataFrame with columns:
        subject_index, block_index, trial_number, bound, abs_bound,
        RT, DT, change_point, choice, correct, coin_count, snr,
        steps, congruence, rt_cutoff, rt_below_cutoff, wall_hit
    """
    # 'MX' membership covers 'MX' and 'MXSC' (online mixed-SNR column layout,
    # snr computation, and bound extraction); 'SC' membership covers 'MXSC'
    # (adds a per-trial change_point column). Mirrors MATLAB's contains(...).
    is_ol_or_mx = task_type == "OL" or "MX" in task_type
    is_sc = "SC" in task_type

    # data_dir/<task_type>/*.csv -- a flat copy of the raw data, unpacked from
    # the frozen archive data/pigeon_raw_human.tar.gz (see pathDefaults.RAW_DATA_DIR
    # and scripts/unpack_data.sh), one folder per task type (MX/, MXSC/, OL/, PD/),
    # no Pigeon_ prefix or prolificcsvs/ subfolder (unlike the original external
    # Box/GoldWorks source layout this was copied from). MXSC (change-point task)
    # lives alongside the other task types here -- no separate CP-specific data
    # directory is needed.
    csv_pattern = os.path.join(data_dir, task_type, "*.csv")
    files = sorted(glob.glob(csv_pattern))

    # 'mean' vs 'median' subjects ran different task-code versions that
    # derived the CP step differently -- see _load_mxsc_cp_methods and the
    # is_sc block below.
    cp_methods = _load_mxsc_cp_methods() if is_sc else {}

    all_tables = []

    for subject_index, fpath in enumerate(files, start=1):
        raw = pd.read_csv(fpath, encoding="utf-8-sig")

        lg = raw["trial_number"].notna()
        if isinstance(blocks, list):
            lg = lg & raw["block_number"].isin(blocks)

        if task_type == "PD":
            # PD CSVs interleave trial-metadata rows (trial_number present) with
            # pigeon-data rows (trial_number absent). Access next_rows from the
            # raw DataFrame before filtering so the i+1 index is always valid.
            # step_mean_val/step_std_val (for SNR) live on the metadata row
            # alongside predefined_bound/correct, not on the data row.
            orig_idx = raw.index[lg].tolist()
            orig_idx = [i for i in orig_idx if i + 1 < len(raw)]  # drop if no following row
            trial_rows = raw.loc[orig_idx].reset_index(drop=True)
            next_rows  = raw.loc[[i + 1 for i in orig_idx]].reset_index(drop=True)
            tmp = pd.concat([
                trial_rows[["block_number", "trial_number", "predefined_bound", "correct",
                            "step_mean_val", "step_std_val"]],
                next_rows[["pigeon_steps", "choice", "coins_count"]],
            ], axis=1)
        else:
            tmp = raw[lg].reset_index(drop=True)
            if is_ol_or_mx:
                cols = ["block_number", "trial_number", "pigeon_steps", "choice",
                        "correct", "steps_count", "step_mean_val", "step_std_val", "coins_count"]
                # switch_time is only present in MXSC data collected with the
                # task-code version that records the changepoint step directly
                # (see the is_sc block below); older files predate this column.
                if is_sc and "switch_time" in tmp.columns:
                    cols.append("switch_time")
                tmp = tmp[cols].copy()

        n_trials = len(tmp)
        block_index = tmp["block_number"].to_numpy(dtype=float)
        if is_sc and "switch_time" not in tmp.columns:
            # Legacy MXSC conditions-file layout (pre-dates both switch_time
            # recording and the removal of the middle block): raw blocks were
            # 1=fixed-low, 2=fixed-high, 3=a mixed-SNR block unrelated to the
            # change-point analysis and unused by any current code, 4=LowHigh
            # CP, 5=HighLow CP. The current layout (has switch_time) is
            # 1=fixed-low, 2=fixed-high, 3=LowHigh CP, 4=HighLow CP. Remap the
            # legacy numbering onto the current one -- 4->3, 5->4 -- so both
            # eras share one canonical block_index and downstream code
            # (get_bound_summaries_wcp, this function's lh_block/hl_block
            # below) doesn't need to know which era a given file is from.
            # Legacy raw block 3 is pushed to -1 (out of the 1-4 canonical
            # range) rather than left at 3, so it can never silently alias
            # onto the current layout's LowHigh-CP block.
            block_index = pd.Series(block_index).replace({4: 3, 5: 4, 3: -1}).to_numpy(dtype=float)
        rows = {
            "subject_index": np.full(n_trials, subject_index),
            "block_index": block_index,
            "trial_number": tmp["trial_number"].to_numpy(dtype=float),
            "bound": np.full(n_trials, np.nan),
            "abs_bound": np.full(n_trials, np.nan),
            "RT": np.full(n_trials, np.nan),
            "DT": np.full(n_trials, np.nan),
            "change_point": np.zeros(n_trials),
            "choice": np.full(n_trials, np.nan),
            "correct": np.full(n_trials, np.nan),
            # PD's coins_count column occasionally holds a block-end bonus
            # message ("No bonus" / "Bonus!") instead of a running total --
            # a PsychoPy logging quirk that overwrites the last trial of each
            # block. coerce=NaN rather than crashing; coin_count isn't used by
            # any bound/DT analysis.
            "coin_count": pd.to_numeric(tmp["coins_count"], errors="coerce").to_numpy(dtype=float),
            "snr": (tmp["step_mean_val"] / tmp["step_std_val"]).to_numpy(dtype=float),
            # Per-step noise SD; with snr this recovers the generative mean
            # (|snr| * step_std) that CP calibrations must be simulated at.
            "step_std": tmp["step_std_val"].abs().to_numpy(dtype=float),
            "steps": [None] * n_trials,
            "congruence": [None] * n_trials,
            "rt_cutoff": np.ones(n_trials),
        }

        # Parse steps and choices per trial
        for tt in range(n_trials):
            steps_str = tmp["pigeon_steps"].iloc[tt]
            if isinstance(steps_str, str):
                steps = np.array([float(x) for x in steps_str.strip('[]').split(',') if x.strip()], dtype=float)
            else:
                steps = np.array([], dtype=float)
            rows["steps"][tt] = steps

            choice_val = tmp["choice"].iloc[tt]
            if isinstance(choice_val, str) and choice_val in ("right", "left"):
                rows["choice"][tt] = 1.0 if choice_val == "right" else 0.0
                correct_val = tmp["correct"].iloc[tt]
                if isinstance(correct_val, str):
                    rows["correct"][tt] = 1.0 if choice_val == correct_val else 0.0
            elif isinstance(choice_val, (int, float)) and np.isfinite(choice_val):
                rows["choice"][tt] = float(choice_val)
                rows["correct"][tt] = float(tmp["correct"].iloc[tt])

            if task_type == "PD":
                rows["RT"][tt] = len(steps)
                # The bound is chosen by the subject before the trial starts
                # (hence "predefined") -- there's no midpoint estimation from
                # step positions, so sign it directly by choice direction
                # (right=+, matching the sign convention get_bounds derives
                # from step position elsewhere: positive = right). Leave NaN
                # if choice wasn't parsed (unsigned bound would be meaningless).
                if np.isfinite(rows["choice"][tt]):
                    sign = 1.0 if rows["choice"][tt] == 1.0 else -1.0
                    rows["bound"][tt] = sign * float(tmp["predefined_bound"].iloc[tt])

        # Change-point tasks (e.g. 'MXSC'): canonical blocks 1/2 are the
        # pre-change low/high-SNR blocks, 3/4 the post-change low-to-high (LH)
        # and high-to-low (HL) blocks (block_index above is already remapped
        # onto this canonical numbering for legacy-layout files).
        #
        # Computed before the get_bounds call below (rather than after, as in
        # the original translation) so that change_point can be passed into
        # it -- see get_bounds' `change_point` parameter and
        # exclude_switched_trials_from_ndt above. This only needs RT, not any
        # NDT-derived quantity, so a cheap local RT (steps taken, ignoring
        # NaN padding) stands in for get_bounds' own `rts` output, which
        # doesn't exist yet at this point.
        if is_sc:
            block_idx = rows["block_index"]
            lh_block = block_idx == 3
            hl_block = block_idx == 4
            change_point = np.zeros(n_trials)
            raw_rt = np.array(
                [len(s[np.isfinite(s)]) if s is not None else 0 for s in rows["steps"]],
                dtype=float,
            )

            if "switch_time" in tmp.columns:
                # Current task code: the changepoint step is recorded
                # directly, per trial, in switch_time -- read it rather than
                # re-deriving it from RTs (see task/MXSC/PigeonTask.js's
                # otr_code_update "Begin Routine"). Only lh_block/hl_block
                # trials have a real value; leave everything else at 0 (no
                # changepoint). A NaN switch_time on an lh/hl trial would
                # mean the task failed to record it -- surfaced, not silently
                # zeroed, since that should never happen with this task-code
                # version.
                st = pd.to_numeric(tmp["switch_time"], errors="coerce").to_numpy(dtype=float)
                change_point = np.where(lh_block | hl_block, st, 0.0)
            elif not lh_block.any() and not hl_block.any():
                # No switch_time column AND no LH/HL trials at all: this is
                # not a legacy-format file that completed the task under an
                # older CP-timing formula, it's a modern session that was
                # abandoned before reaching a change_low/change_high block
                # (e.g. dropped out partway through block 1) -- switch_time
                # is only ever logged inside those blocks (see
                # otr_code_update "Begin Routine" in task/MXSC/PigeonTask.js),
                # so PsychoPy never created the column for a session that
                # never got there. There's no changepoint to derive (no LH/HL
                # rows to derive it from), so change_point stays all-zero
                # (no-change data) and this subject is naturally excluded
                # downstream (nonfinite pre-/post-CP bound) without needing
                # an mxsc_cp_method.txt entry.
                pass
            else:
                # Older data predates the switch_time column but does have
                # LH/HL trials: fall back to recomputing the changepoint from
                # RTs, using whichever formula that subject's task-code
                # version actually used online (see _load_mxsc_cp_methods):
                # 'mean' -> round(mean(RT)) (matches
                # matlab/getPigeon_dataTable_MXSC.m); 'median' -> unrounded
                # median(RT) (matches the pre-fix calculate_median() in
                # task/MXSC/PigeonTask.js).
                fname = os.path.basename(fpath)
                if fname not in cp_methods:
                    raise KeyError(
                        f"{fname!r} has no entry in {MXSC_CP_METHOD_FILE} -- "
                        "add it (mean or median) before computing change_point."
                    )
                cp_method = cp_methods[fname]
                cp_func = (lambda x: round(np.nanmean(x))) if cp_method == "mean" \
                    else np.nanmedian

                rt = raw_rt
                l_block = block_idx == 1
                h_block = block_idx == 2
                # 'median' subjects with an even-length fixed block get a
                # half-integer CP (average of the two middle RTs). That
                # task-code version never rounded this and triggered the
                # switch with strict equality against an integer step
                # counter (steps_in_trial === switch_time), so a
                # half-integer switch_time could never match -- the SNR
                # switch never actually fired online for that block. NaN it
                # out here (rather than rounding to a step that was never
                # really reached) so downstream code treats the whole block
                # as no-change data and excludes it from CP-specific analyses.
                if l_block.any() and lh_block.any():
                    cp_val = cp_func(rt[l_block])
                    change_point[lh_block] = cp_val if float(cp_val) % 1 == 0 else np.nan
                if h_block.any() and hl_block.any():
                    cp_val = cp_func(rt[h_block])
                    change_point[hl_block] = cp_val if float(cp_val) % 1 == 0 else np.nan

            rows["change_point"] = change_point

        # Compute bounds, DT, RT, congruences for online tasks
        if is_ol_or_mx:
            bounds, dts, rts, congruence, rt_cutoffs = get_bounds(
                rows["steps"], rows["choice"],
                snr=np.abs(rows["snr"]),
                block_ids=rows["block_index"],
                ndt=None,
                max_ndt=max_ndt,
                peak_step_bound=peak_step_bound,
                change_point=(rows["change_point"]
                              if is_sc and exclude_switched_trials_from_ndt else None),
            )
            rows["bound"]      = bounds
            rows["DT"]         = dts
            rows["RT"]         = rts
            rows["congruence"] = [congruence] * n_trials
            rows["rt_cutoff"]  = rt_cutoffs
        elif task_type == "PD":
            # No NDT to subtract -- the subject already knows the bound, so
            # every step taken is deliberation time.
            rows["DT"] = rows["RT"].copy()

        rows["abs_bound"] = np.abs(rows["bound"])

        all_tables.append(pd.DataFrame(rows))
        
    data_table = pd.concat(all_tables, ignore_index=True)

    # Flag trials below the per-(subject, block, SNR) RT reliability cutoff.
    data_table["rt_below_cutoff"] = data_table["RT"] < data_table["rt_cutoff"]

    # Mark trials where the pigeon reached the screen edge (|step| >= WALL).
    # On these trials the step logger kept recording after the wall was hit,
    # inflating RT and DT. The wall-hit step itself is the true end of the trial.
    data_table["wall_hit"] = data_table["steps"].apply(
        lambda s: s is not None and len(s) > 0
        and bool(np.any(np.abs(s[np.isfinite(s)]) >= WALL - 1e-9))
    )

    # Combine 6 blocks into 3 if requested. Never applies to change-point (SC)
    # data: blocks 1-6 there are not a blocked-vs-mixed duplicate of the same
    # 3 conditions (as in MX/OL/PD) but distinct fixed/change-point conditions,
    # so remapping or dropping blocks 4-6 would destroy the change-point
    # structure that get_bound_summaries_wcp depends on.
    if combine_snr and not is_sc and sorted(data_table["block_index"].dropna().unique().astype(int)) == list(range(1, 7)):
        block1_snrs = data_table.loc[data_table["block_index"] == 1, "snr"].dropna()
        if len(block1_snrs.abs().unique()) == 1:
            # blocked: remap blocks 4-6 -> 1-3
            for b in range(1, 4):
                data_table.loc[data_table["block_index"] == b + 3, "block_index"] = b
        else:
            # mixed: drop blocks 4-6
            data_table = data_table[data_table["block_index"] <= 3].reset_index(drop=True)

    # Apply bias corrections. Never for PD: its bound is chosen by the subject
    # (not estimated from step positions), so there's no measurement bias to
    # correct -- the calibration files are specific to the midpoint estimator
    # used by the other task types and would corrupt PD's exact bounds.
    if correct_bias and task_type != "PD" and os.path.exists(correct_bias):
        if is_sc:
            # CP SNRs are fixed by the task design (not staircase-calibrated
            # per subject as in MX/OL), so the calibration must have been
            # simulated at exactly the SNRs in the data. Fail loudly rather
            # than silently binning trials into a calibration built for a
            # different design (as happened when the 2026 task raised high
            # SNR from 0.4 to 0.6).
            calib = scipy.io.loadmat(correct_bias, squeeze_me=True)
            if "snrs" not in calib:
                raise ValueError(f"{correct_bias} has no 'snrs' field; cannot verify it matches the CP data.")
            check_calibration_snrs(calib["snrs"], data_table, source=correct_bias)
        data_table = apply_bias_corrections(data_table, correct_bias)

    return data_table


def _compute_rt_cutoff(bound_matrix, choices_pm, rts, threshold=0.65, min_trials=5):
    """
    Find the minimum RT cutoff C such that trials with RT >= C have
    max congruence (across NDT lags) >= threshold.

    Iterates from the largest RT down to the smallest. At each candidate
    cutoff r, computes max_k(congruence) for all trials with RT >= r.
    Returns the smallest r for which this still meets the threshold.

    Parameters
    ----------
    bound_matrix : (n_trials, max_ndt) array
    choices_pm   : (n_trials,) array  —  choices coded as ±1
    rts          : (n_trials,) array  —  response times
    threshold    : float              —  congruence threshold (default 0.65)
    min_trials   : int                —  minimum trials per RT bin to compute congruence

    Returns
    -------
    int : minimum RT to include (exclude trials with RT < cutoff).
          Returns 1 if all RTs meet the threshold (no cutoff needed).
    """
    max_ndt  = bound_matrix.shape[1]
    rt_vals  = sorted(np.unique(rts[np.isfinite(rts)].astype(int)))
    cutoff   = 1  # default: no cutoff needed

    for r in reversed(rt_vals):
        mask = np.isfinite(rts) & (rts.astype(int) >= r)
        if mask.sum() < min_trials:
            continue
        max_cong = 0.0
        for k in range(max_ndt):
            lc = mask & (bound_matrix[:, k] != 0)
            if lc.sum() >= min_trials:
                cong = np.mean(np.sign(bound_matrix[lc, k]) == choices_pm[lc])
                max_cong = max(max_cong, cong)
        if max_cong >= threshold:
            cutoff = r   # threshold met; try including one shorter RT
        else:
            break        # adding shorter RT drops below threshold; stop

    return cutoff


def get_bounds(steps_list, choices, min_rt=1, snr=None,
               block_ids=None, rt_cutoff_threshold=0.65, ndt=2,
               max_ndt=5, peak_step_bound=True, change_point=None):
    """
    Compute bounds, decision times, response times, and congruences.
    Translated from getPigeon_bounds.m

    Parameters
    ----------
    steps_list : list of np.ndarray
    choices : array-like of float (0/1)
    min_rt : int
    snr : array-like or None
        Per-trial |SNR|. Used only to pick out the lowest-SNR condition for
        NDT estimation when `ndt=None` (see below) -- has no other effect.
        One call to `get_bounds` is assumed to cover a single subject's
        trials (this is how `get_data_table` calls it); passing pooled
        multi-subject data would estimate one NDT for the whole pool.
    block_ids : array-like or None
        Block identifier per trial. If provided, the RT cutoff is computed
        separately for each (block, SNR) combination. If None, a single
        cutoff is computed across all trials.
    rt_cutoff_threshold : float
        Congruence threshold for the RT cutoff (default 0.65). Set to None
        to skip cutoff computation (rt_cutoffs returned as all-ones).
    ndt : int or None
        NDT lag to use for bound extraction. If an integer, all trials use
        this fixed lag (clipped to RT-2). If None, a single NDT lag is
        estimated for all trials in this call -- see "NDT estimation" below.
    max_ndt : int
        Max NDT lag considered when building the bound matrix (default 5;
        must be >= 4 to support the [1, 3] NDT search below).
    peak_step_bound : bool
        If True (default), apply the peak-step bound correction: for trials
        where the pigeon is moving away from the choice side at the NDT
        crossing, replace the midpoint bound with steps[RT-2-ndt] — the
        earlier, outermost of the two crossing steps (furthest from centre).
        This is a Python-only addition not present in getPigeon_bounds.m at
        all; applied uniformly to every task type (MX/OL/PD/MXSC).
    change_point : array-like or None
        Per-trial changepoint step (switch_time), 0/NaN for non-changepoint
        trials -- as in `data_table["change_point"]`. Only used (when
        `ndt=None`) to exclude "contaminated" trials from the lowest-SNR NDT
        pool: a changepoint trial whose RT exceeds its own change_point
        actually crossed into the other (noisier, bigger-step) SNR regime
        before the response, even though it is still labeled with its
        pre-switch `snr`. Left in, these trials dilute/bias the low-SNR
        congruence curve the NDT search relies on (see notebooks/Test_NDT.ipynb
        Part 2 for why that curve's shape is SNR-dependent in the first
        place). Has no effect when `ndt` is an explicit integer, or when
        `change_point` is None (default -- matches every non-changepoint
        caller, which has nothing to pass here).

    NDT estimation (when ndt=None)
    -------------------------------
    A single NDT lag is estimated from this call's lowest-|SNR| trials only
    (not pooled across SNR, not estimated separately per SNR group), then
    applied to every trial regardless of its own SNR. Lower SNR means the
    pigeon's position more often drifts backward after the true bound
    crossing, which is what lets the congruence-vs-lag curve sharply
    localize the true crossing lag; at higher SNR the position rarely
    reverses, so the curve stays flat across several lags and doesn't
    cleanly identify one -- pooling across SNR, or estimating separately per
    SNR group, both end up letting that flat, uninformative high-SNR curve
    pull the estimate toward lags that aren't really about NDT (confirmed on
    real MX/OL data: pooled and per-SNR-group estimates disagreed for
    17-23% of subjects, consistently toward higher lags for the per-SNR
    high-SNR estimate). The search itself is restricted to lags 1-3: NDT=0
    (zero motor delay) and NDT>=4 aren't physiologically plausible, so an
    unrestricted argmax landing there almost certainly reflects estimation
    noise rather than a real value; restricting the search (rather than
    clamping an out-of-range answer) picks the best still-plausible lag
    instead. Ties broken toward the largest lag. See notebooks/Test_NDT.ipynb
    for the analysis behind this.

    Returns
    -------
    bounds : np.ndarray
    dts : np.ndarray
    rts : np.ndarray
    congruences : np.ndarray, shape (max_ndt, n_snrs)
        Per-SNR-group congruence, for diagnostics only -- NDT estimation
        itself only uses the lowest-SNR column, and only lags 1-3 of it.
    rt_cutoffs : np.ndarray, shape (n_trials,)
        Per-trial RT cutoff. Trials with RT < rt_cutoffs[i] are below the
        reliability threshold and should be excluded from bound analyses.
    """
    n_trials = len(steps_list)
    choices_pm = np.array(choices) * 2 - 1  # convert 0/1 to -1/+1

    if snr is None:
        snr = np.zeros(n_trials)
    snr = np.asarray(snr)
    unique_snrs = np.unique(snr[np.isfinite(snr)])
    n_snrs = len(unique_snrs)

    if block_ids is None:
        block_ids = np.zeros(n_trials)
    block_ids = np.asarray(block_ids)

    # Build the bound matrix.
    # For each trial, take the last min(RT, max_ndt) step positions, reverse them,
    # and compute midpoints between consecutive pairs.  The midpoint at lag k is:
    #   bound_matrix[i, k] = (steps[RT-1-k] + steps[RT-2-k]) / 2
    # This estimates where the accumulator was when the decision threshold was crossed
    # at NDT lag k steps before the response.
    bound_matrix = np.zeros((n_trials, max_ndt))
    rts = np.full(n_trials, np.nan)

    for ii in range(n_trials):
        these_steps = steps_list[ii]
        these_steps = these_steps[np.isfinite(these_steps)] if these_steps is not None else np.array([])
        rts[ii] = len(these_steps)

        # MATLAB's steps{ii}(max(rts-maxNDT,1):end) is a 1-indexed, inclusive
        # slice of length maxNDT+1 (when rts>maxNDT); the equivalent 0-indexed
        # start is max(rts-maxNDT,1)-1 = max(rts-maxNDT-1,0), not max(rts-maxNDT,0)
        # (that under-counts by one element and silently drops the deepest NDT lag).
        final_steps = these_steps[max(int(rts[ii]) - max_ndt - 1, 0):][::-1]  # reversed
        if len(final_steps) > 1:
            # midpoints between consecutive pairs
            midpoints = final_steps[1:] - np.diff(final_steps) / 2
            bound_matrix[ii, :len(midpoints)] = midpoints

    # Per-SNR-group congruence, for diagnostics only (see docstring).
    # Congruence at lag k = fraction of trials where sign(bound_matrix[:, k])
    # matches the choice direction (+1 = right, -1 = left).
    ndts = np.full(n_trials, np.nan)
    bounds = np.full(n_trials, np.nan)
    congruences = np.full((max_ndt, n_snrs), np.nan)

    for ss, snr_val in enumerate(unique_snrs):
        ls = np.isclose(snr, snr_val)
        for ii in range(max_ndt):
            lc = ls & (bound_matrix[:, ii] != 0)
            if lc.sum() > 5:
                congruences[ii, ss] = np.sum(
                    np.sign(bound_matrix[lc, ii]) == choices_pm[lc]
                ) / lc.sum()

    if ndt is not None:
        # Fixed NDT lag, same for every trial (used by calibration/simulation
        # callers that already know the ground-truth NDT).
        ndts[:] = np.clip(rts - 2, 0, int(ndt))
    else:
        # Estimate a single NDT lag from the lowest-|SNR| trials only, search
        # restricted to lags 1-3, then apply it to every trial in this call
        # regardless of SNR -- see "NDT estimation" in the docstring.
        low_snr_val = unique_snrs.min() if n_snrs > 0 else 0.0
        ls = np.isclose(snr, low_snr_val)
        if change_point is not None:
            change_point = np.asarray(change_point, dtype=float)
            # A changepoint trial is labeled with its pre-switch snr even if
            # it ran long enough to cross into the post-switch regime -- drop
            # those "contaminated" trials from the low-SNR NDT pool (see the
            # `change_point` docstring entry above).
            switched = (change_point > 0) & (rts > change_point)
            ls = ls & ~switched
        low_snr_cong = np.full(max_ndt, np.nan)
        for ii in range(1, min(4, max_ndt)):
            lc = ls & (bound_matrix[:, ii] != 0)
            if lc.sum() > 5:
                low_snr_cong[ii] = np.sum(
                    np.sign(bound_matrix[lc, ii]) == choices_pm[lc]
                ) / lc.sum()
        if np.any(np.isfinite(low_snr_cong)):
            max_cong = np.nanmax(low_snr_cong)
            ci = int(np.where(low_snr_cong == max_cong)[0][-1])  # ties -> largest lag
            ndts[:] = np.clip(rts - 2, 0, ci)

    # Extract bound for each trial from its NDT lag.
    # With peak_step_bound=True: for trials where the pigeon is moving away from
    # the choice side at the NDT crossing, replace the midpoint with steps[RT-2-k]
    # (the earlier, outermost step — furthest from centre when retreating).
    for tt in np.where(np.isfinite(ndts))[0]:
        k   = int(ndts[tt])
        mid = bound_matrix[tt, k]

        if peak_step_bound and mid != 0:
            sc = steps_list[tt]
            sc = sc[np.isfinite(sc)] if sc is not None else np.array([])
            RT       = int(rts[tt])
            t_later  = RT - 1 - k   # later step (closer to response)
            t_earlier = RT - 2 - k  # earlier step (furthest from centre when retreating)
            if 0 <= t_earlier < len(sc) and t_later < len(sc):
                step_in = sc[t_later] - sc[t_earlier]
                if step_in * np.sign(mid) < 0:  # backward motion at crossing
                    bounds[tt] = sc[t_earlier]
                    continue

        bounds[tt] = mid

    # Remove bounds from very short trials
    bounds[rts < min_rt] = np.nan

    # DT = steps after the NDT period ends (i.e. the "deliberation time")
    dts = np.maximum(0, rts - ndts - 1)

    # Compute RT cutoff per (block, SNR) group.
    # For each group, find the minimum RT such that trials with RT >= that value
    # have max congruence (across NDT lags) >= rt_cutoff_threshold.
    rt_cutoffs = np.ones(n_trials, dtype=float)
    if rt_cutoff_threshold is not None:
        for blk in np.unique(block_ids[np.isfinite(block_ids.astype(float))]):
            for snr_val in unique_snrs:
                group = (np.isclose(block_ids.astype(float), float(blk)) &
                         np.isclose(snr, snr_val))
                if group.sum() < 5:
                    continue
                cutoff = _compute_rt_cutoff(
                    bound_matrix[group],
                    choices_pm[group],
                    rts[group],
                    threshold=rt_cutoff_threshold,
                )
                rt_cutoffs[group] = cutoff

    return bounds, dts, rts, congruences, rt_cutoffs


def get_bounds_from_dv(choices, rts, DV, max_ndt=5, rt_cutoff_threshold=0.65,
                        ndt=2, peak_step_bound=True):
    """
    Like get_bounds but takes a pre-built DV matrix instead of a steps list.

    Intended for vectorised use with simulation output (e.g. bias-correction
    calibration) where DV is already a 2-D numpy array.  The bound logic —
    midpoint construction, NDT selection, peak-step correction, RT cutoff — is
    identical to get_bounds.

    Parameters
    ----------
    choices : (n,) array-like  0 = left, 1 = right
    rts     : (n,) array-like  number of steps taken per trial
    DV      : (n, max_steps) float array  DV[i, t] = pigeon position at step t
    max_ndt : int
    rt_cutoff_threshold : float or None
    ndt     : int or None  fixed NDT lag; None -> pick by max congruence
    peak_step_bound : bool  see get_bounds

    Returns
    -------
    bounds, dts, rts, congruence, rt_cutoffs
        Same semantics as get_bounds; congruence has shape (max_ndt,) with
        no SNR dimension (caller supplies one SNR group at a time).
    """
    n_trials   = len(choices)
    rts        = np.asarray(rts,     dtype=float)
    choices_pm = np.asarray(choices, dtype=float) * 2 - 1

    # ── Build bound matrix (vectorised) ──────────────────────────────────────
    # bound_matrix[i, k] = (DV[i, RT-1-k] + DV[i, RT-2-k]) / 2
    bound_matrix = np.zeros((n_trials, max_ndt))
    for k in range(max_ndt):
        rows = np.where(rts >= k + 2)[0]
        if len(rows):
            r = rts[rows].astype(int)
            bound_matrix[rows, k] = (DV[rows, r - 1 - k] + DV[rows, r - 2 - k]) / 2

    # ── NDT selection ────────────────────────────────────────────────────────
    congruence = np.full(max_ndt, np.nan)
    for k in range(max_ndt):
        lc = bound_matrix[:, k] != 0
        if lc.sum() > 5:
            congruence[k] = np.mean(np.sign(bound_matrix[lc, k]) == choices_pm[lc])

    ndts = np.full(n_trials, np.nan)
    if ndt is not None:
        ndts[:] = np.clip(rts - 2, 0, int(ndt))
    else:
        if np.any(np.isfinite(congruence)):
            max_cong = np.nanmax(congruence)
            ci = int(np.where(congruence == max_cong)[0][-1])
            ndts[:] = np.clip(rts - 2, 0, ci)

    # ── RT cutoff ────────────────────────────────────────────────────────────
    rt_cutoffs = np.ones(n_trials, dtype=float)
    if rt_cutoff_threshold is not None:
        rt_cutoffs[:] = _compute_rt_cutoff(
            bound_matrix, choices_pm, rts, threshold=rt_cutoff_threshold
        )

    # ── Extract bounds with peak-step correction ──────────────────────────────
    bounds = np.full(n_trials, np.nan)
    for tt in np.where(np.isfinite(ndts))[0]:
        k   = int(ndts[tt])
        mid = bound_matrix[tt, k]

        if peak_step_bound and mid != 0:
            RT        = int(rts[tt])
            t_later   = RT - 1 - k
            t_earlier = RT - 2 - k
            if 0 <= t_earlier < DV.shape[1] and t_later < DV.shape[1]:
                step_in = DV[tt, t_later] - DV[tt, t_earlier]
                if step_in * np.sign(mid) < 0:
                    bounds[tt] = DV[tt, t_earlier]
                    continue
        bounds[tt] = mid

    # ── DTs ──────────────────────────────────────────────────────────────────
    dts = np.maximum(0, rts - ndts - 1)

    return bounds, dts, rts, congruence, rt_cutoffs


def get_good_trial_array(data_table, min_dt=2, min_trial_number=10,
                         block_index=None, apply_rt_cutoff=True):
    """
    Standard trial selection filter.
    Translated from getPigeon_goodTrialArray.m

    Parameters
    ----------
    data_table : pd.DataFrame
        Output of get_data_table (or get_simulated_data_table).
    min_dt : int or None
        Minimum DT (decision time, steps). Excludes trials too short to
        estimate a reliable bound. Default 2.
    min_trial_number : int or None
        Minimum trial number within a block. Excludes early warm-up trials
        where participants are still learning the task. Default 10.
    block_index : int, list, or None
        If given, keep only trials from the specified block(s).
    apply_rt_cutoff : bool
        If True and 'rt_below_cutoff' column is present, excludes trials
        below the per-(block, SNR) RT reliability cutoff computed in
        get_bounds. Default True.

    Returns
    -------
    pd.Series of bool, same index as data_table.
        True for trials that pass all filters (i.e. should be included
        in bound and performance analyses).
    """
    lg = pd.Series(True, index=data_table.index)

    if min_dt is not None:
        lg = lg & (data_table["DT"] >= min_dt)
    if min_trial_number is not None:
        lg = lg & (data_table["trial_number"] >= min_trial_number)
    if block_index is not None:
        lg = lg & data_table["block_index"].isin(
            [block_index] if np.isscalar(block_index) else block_index
        )
    # Exclude wall-hit trials: pigeon reached screen edge, inflating RT/DT
    if "wall_hit" in data_table.columns:
        lg = lg & ~data_table["wall_hit"]
    # Exclude trials below the per-(subject, block, SNR) RT reliability cutoff
    if apply_rt_cutoff and "rt_below_cutoff" in data_table.columns:
        lg = lg & ~data_table["rt_below_cutoff"]

    return lg


def apply_bias_corrections(data_table, bias_file):
    """
    Apply bound bias corrections loaded from a .mat file.

    Prefers interpolation on the full calibration table when ``boundSummary``
    and ``simBounds`` are present in the file (generated by the current
    ``Make_biasCorrection.ipynb``).  Falls back to the legacy linear-fit
    coefficients (``boundBiasCorrection``) for older files.

    Interpolation approach
    ----------------------
    The calibration table stores the mean *measured* bound for each combination
    of true generative bound, DT bin, and SNR bin.  The correction inverts this
    curve: given a measured bound M, ``np.interp`` returns the true bound T such
    that the calibration curve passes through (M, T).  This handles the
    nonlinearity at small bounds (|bound| < σ = 0.15) that a single linear fit
    cannot capture.

    Legacy linear approach
    ----------------------
    Translated from getPigeon_biasCorrections.m.
    ``corrected = max(0.005, a + b * |measured|)`` per (DT bin, SNR bin), where
    [a, b] = ``boundBiasCorrection[dd, :, mm]``.  Less accurate at small bounds.

    Out-of-calibration-range measured bounds (interpolation approach only)
    ------------------------------------------------------------------------
    For short-DT bins the calibration table often has valid data only up to a
    modest true bound -- larger true bounds essentially never resolve in few
    steps, so those simulated cells are NaN and get dropped from the curve
    (see ``Make_biasCorrection.ipynb``, Part 2). A real trial with a measured bound
    beyond the calibrated range is linearly extrapolated from the curve's edge
    slope, rather than clamped to the boundary value the way plain
    ``np.interp`` would (which silently caps every such trial at whatever the
    most extreme calibration point produced -- see git history for the
    magnitude of the resulting distortion).

    SNR bins (both approaches)
    --------------------------
    ``snrBinEdges`` in the calibration file defines the bin edges (N edges ->
    N+1 bins, ``np.digitize`` semantics: bin i is
    ``edges[i-1] <= |snr| < edges[i]``). Falls back to the legacy MX/OL/PD
    edges ``[0.4, 0.8]`` (3 bins: low/mid/high, tuned to that task's SNR
    range) for calibration files that don't carry the field. Trials with
    non-finite |snr| are excluded from every bin (left uncorrected), matching
    the legacy hardcoded-mask behavior.

    Parameters
    ----------
    data_table : pd.DataFrame
        Output of get_data_table (or get_simulated_data_table). Must contain
        'bound' and 'snr' columns.
    bias_file : str
        Path to a .mat calibration file generated by
        notebooks/Make_biasCorrection.ipynb.

    Returns
    -------
    pd.DataFrame
        Copy of data_table with 'bound' and 'abs_bound' replaced by their
        bias-corrected values.
    """
    mat = scipy.io.loadmat(bias_file)

    edges = np.asarray(mat["snrBinEdges"]).ravel() if "snrBinEdges" in mat else np.array([0.4, 0.8])
    n_snr_bins = len(edges) + 1

    snrs = np.abs(data_table["snr"].to_numpy())
    lsnr_finite = np.isfinite(snrs)
    snr_bin = np.digitize(snrs, edges)  # bin i: edges[i-1] <= snr < edges[i]
    snr_masks = np.column_stack([lsnr_finite & (snr_bin == mm) for mm in range(n_snr_bins)])

    bounds = data_table["bound"].to_numpy(dtype=float).copy()

    use_interp = "boundSummary" in mat and "simBounds" in mat

    if use_interp:
        # boundSummary[ss, dt_idx, mm] = mean measured bound for true bound
        # simBounds[ss] at DT bin dt_idx+1 and SNR bin mm.
        bound_summary = mat["boundSummary"]       # (n_bounds, n_dt_bins, n_snr_bins)
        sim_bounds    = mat["simBounds"].ravel()  # (n_bounds,)
        n_dts         = bound_summary.shape[1]
    else:
        bias_correction = mat["boundBiasCorrection"]  # (n_dt_bins, 2, n_snr_bins)
        n_dts           = bias_correction.shape[0]

    # The last DT bin is open-ended (DT >= n_dts) to cover very long trials.
    # A floor of 0.005 prevents degenerate near-zero corrected bounds.
    for dd in range(n_dts):
        ld = (data_table["DT"] == (dd + 1)) if dd < n_dts - 1 else (data_table["DT"] >= (dd + 1))

        for mm in range(n_snr_bins):
            ls = ld & snr_masks[:, mm]
            if not ls.any():
                continue

            abs_b = np.abs(bounds[ls])

            if use_interp:
                x = bound_summary[:, dd, mm]  # measured bound at each calibration point
                lvalid = np.isfinite(x)
                if lvalid.sum() < 2:
                    continue
                # Sort by x to guarantee a monotone interpolation grid.
                order = np.argsort(x[lvalid])
                xv, yv = x[lvalid][order], sim_bounds[lvalid][order]
                corrected = np.maximum(0.005, _interp_with_extrapolation(abs_b, xv, yv))
            else:
                corrected = np.maximum(
                    0.005,
                    bias_correction[dd, 0, mm] + bias_correction[dd, 1, mm] * abs_b,
                )

            bounds[ls] = np.sign(bounds[ls]) * corrected

    data_table = data_table.copy()
    data_table["bound"]     = bounds
    data_table["abs_bound"] = np.abs(bounds)
    return data_table


def _interp_with_extrapolation(x, xv, yv):
    """
    Like ``np.interp``, but linearly extrapolates past the edges of
    ``(xv, yv)`` instead of clamping to the boundary value. ``xv`` must be
    sorted ascending with at least 2 points.
    """
    x = np.asarray(x, dtype=float)
    y = np.interp(x, xv, yv)
    below = x < xv[0]
    above = x > xv[-1]
    if below.any():
        slope = (yv[1] - yv[0]) / (xv[1] - xv[0])
        y[below] = yv[0] + slope * (x[below] - xv[0])
    if above.any():
        slope = (yv[-1] - yv[-2]) / (xv[-1] - xv[-2])
        y[above] = yv[-1] + slope * (x[above] - xv[-1])
    return y


def get_performance_summary(data_table, blocks="all", snrs="all"):
    """
    Compute per-subject/block/SNR accuracy and DT stats.
    Translated from getPigeon_performanceSummary.m

    Parameters
    ----------
    data_table : pd.DataFrame
        Output of get_data_table.
    blocks : 'all' or array-like of int
        'all' uses blocks 1-3; otherwise only the given block(s), in the
        given order.
    snrs : 'all' or array-like of float
        'all' uses every unique |snr| value present in data_table;
        otherwise only the given |snr| value(s), in the given order.

    Returns
    -------
    np.ndarray, shape (n_subjects, n_blocks, n_snrs, 4)
        Last dim: [accuracy, mean_DT, std_DT, n_trials]
    """
    subject_indices = np.sort(data_table["subject_index"].dropna().unique())
    n_subjects = len(subject_indices)

    block_indices = np.arange(1, 4) if blocks == "all" else np.atleast_1d(np.asarray(blocks))
    n_blocks = len(block_indices)

    abs_snr = np.abs(data_table["snr"].to_numpy())
    if snrs == "all":
        abs_snrs = np.sort(np.unique(abs_snr[np.isfinite(abs_snr)]))
    else:
        abs_snrs = np.asarray(snrs)
    n_snrs = len(abs_snrs)

    lg = get_good_trial_array(data_table)

    summary = np.zeros((n_subjects, n_blocks, n_snrs, 4))

    for si, subj in enumerate(subject_indices):
        ls = lg & (data_table["subject_index"] == subj)

        for bi, block in enumerate(block_indices):
            lsb = ls & (data_table["block_index"] == block)

            for ni, snr_val in enumerate(abs_snrs):
                lsnr = lsb & np.isclose(abs_snr, snr_val)
                if lsnr.any():
                    subset = data_table[lsnr]
                    summary[si, bi, ni] = [
                        subset["correct"].sum() / len(subset),
                        subset["DT"].mean(),
                        subset["DT"].std(),
                        len(subset),
                    ]
                else:
                    summary[si, bi, ni] = [np.nan, np.nan, np.nan, 0]

    return summary


def get_bound_summary(data_table, correct_only=False, blocks="all",
                      split_by_snr=True, max_rt=10, subject_indices=None,
                      apply_quality_filter=True):
    """
    Summarize |bound| by subject, block, SNR, and RT/DT.
    Translated from getPigeon_boundSummary.m

    Parameters
    ----------
    data_table : pd.DataFrame
        Output of get_data_table.
    correct_only : bool
        If True, restrict to correct trials only. Default False (all
        trials with a finite choice, i.e. correct in {0, 1}).
    blocks : 'all' or list/scalar of block numbers
        'all' uses every block present in data_table; otherwise only the
        given block(s) are summarized (in the given order).
    split_by_snr : bool
        If True, summarize separately per unique |snr| value -- except for
        change-point blocks (nonzero change_point column), which split on
        pre-/post-changepoint (RT vs change_point) instead: real
        change-point data is staircase-calibrated per subject, so there is
        no small shared set of |snr| values to group by, but grouping on
        the pre-/post-change label still collapses all subjects onto the
        same 2 columns (0 = pre-change, 1 = post-change).
    max_rt : int, 'medsplit', or 'all'
        int   : summarize per DT bin, DT = 1..max_rt
        'medsplit' : median-split by RT into two bins (<= median, > median)
        'all' : collapse across RT/DT into a single bin
    subject_indices : array-like or None
        If given, use this as the fixed subject axis (row order), with NaN
        rows for any subject absent from data_table, instead of deriving it
        from data_table's own unique subject_index values. Needed whenever
        results from multiple get_bound_summary calls (e.g. different block
        subsets, as in get_bound_summaries_wcp) must stay row-aligned to the
        same subject even when some subjects are missing from one subset
        (e.g. a block only present in some sessions) -- without this, each
        call's row axis reflects only the subjects present in that call's
        data_table, so row i can silently refer to different subjects
        across calls.
    apply_quality_filter : bool
        If True (default), also requires get_good_trial_array's standard
        filters (DT >= 2, trial_number >= 10, no wall-hit, and -- if the
        'rt_below_cutoff' column is present -- not below the per-(block,
        SNR) RT reliability cutoff computed in get_bounds). Applied
        uniformly for every caller, including change-point data.

    Returns
    -------
    np.ndarray, shape (n_subjects, n_blocks, n_snrs, n_rt_bins, 3)
        Last axis is [mean |bound|, std |bound|, n trials].
    """
    if subject_indices is None:
        subject_indices = np.sort(pd.unique(data_table["subject_index"].dropna()))
    else:
        subject_indices = np.asarray(subject_indices)
    num_subjects = len(subject_indices)
    abs_bounds = data_table["bound"].abs().to_numpy()

    if blocks == "all":
        block_indices = np.sort(data_table["block_index"].dropna().unique())
    else:
        block_indices = np.atleast_1d(blocks)
    num_blocks = len(block_indices)

    if split_by_snr:
        has_change_point = ("change_point" in data_table.columns
                            and not (data_table["change_point"] == 0).all())
        if has_change_point:
            # Real change-point data is staircase-calibrated per subject, so
            # there is no small shared set of |snr| values to group trials
            # by (each subject's own recorded |snr| is essentially unique).
            # Group on the pre-/post-changepoint label directly instead: all
            # subjects then collapse onto exactly 2 columns (0 = pre-change,
            # i.e. the block's recorded starting condition; 1 = post-change,
            # the condition it switched to), regardless of each subject's
            # actual |snr| magnitude.
            #
            # Compare against RT, not DT: change_point/switch_time is the
            # raw within-trial step count the online task compared against
            # (steps_in_trial === switch_time in task/MXSC/PigeonTask.js),
            # which is the same scale as RT (RT_low/RT_high there are pushed
            # as pigeon_steps.length, i.e. the trial's total step count).
            # DT = RT - NDT is always <= RT, so using DT here systematically
            # undercounts post-change trials -- any trial whose RT landed in
            # (switch_time, switch_time + NDT] would be wrongly bucketed as
            # pre-change, and for some subjects that shrinks the post-change
            # bucket to 0 (e.g. their whole DT distribution can sit at or
            # below switch_time while their RT distribution does not).
            rt_arr = data_table["RT"].to_numpy()
            cp_arr = data_table["change_point"].to_numpy()
            post_change = (cp_arr > 0) & (rt_arr > cp_arr)
            abs_snr = post_change.astype(float)
        else:
            abs_snr = data_table["snr"].abs().to_numpy()

        snrs = np.sort(pd.unique(abs_snr[np.isfinite(abs_snr)]))
        num_snrs = len(snrs)
        l_snrs = np.column_stack([np.isclose(abs_snr, s) for s in snrs]) \
            if num_snrs > 0 else np.zeros((len(data_table), 0), dtype=bool)
    else:
        num_snrs = 1
        l_snrs = np.ones((len(data_table), 1), dtype=bool)

    is_numeric_max_rt = isinstance(max_rt, (int, float)) and not isinstance(max_rt, str)
    if is_numeric_max_rt:
        rt_bins = np.arange(1, int(max_rt) + 1)
    elif max_rt == "medsplit":
        rt_bins = np.arange(1, 3)
    else:  # 'all'
        rt_bins = np.array([1])
    num_rts = len(rt_bins)

    bound_summary_ = np.full((num_subjects, num_blocks, num_snrs, num_rts, 3), np.nan)

    correct = data_table["correct"].to_numpy()
    l_good = (correct == 1) if correct_only else (correct >= 0)
    l_good = l_good & (data_table["bound"].to_numpy() != 0)
    if apply_quality_filter:
        l_good = l_good & get_good_trial_array(data_table).to_numpy()

    block_arr   = data_table["block_index"].to_numpy()
    subject_arr = data_table["subject_index"].to_numpy()
    dt_arr      = data_table["DT"].to_numpy()
    rt_arr      = data_table["RT"].to_numpy()

    def _summarize(mask):
        vals = abs_bounds[mask]
        if vals.size == 0:
            return [np.nan, np.nan, 0]
        # ddof=1 to match MATLAB's std(), which normalizes by N-1, not N.
        return [np.nanmean(vals), np.nanstd(vals, ddof=1), mask.sum()]

    for si, subj in enumerate(subject_indices):
        l_subject = l_good & (subject_arr == subj)

        for bi, blk in enumerate(block_indices):
            l_sb = l_subject & (block_arr == blk)

            for ni in range(num_snrs):
                l_snr = l_sb & l_snrs[:, ni]

                if is_numeric_max_rt:
                    for ri, rt_bin in enumerate(rt_bins):
                        l_rt = l_snr & (dt_arr == rt_bin)
                        bound_summary_[si, bi, ni, ri, :] = _summarize(l_rt)

                elif max_rt == "medsplit":
                    if l_snr.any():
                        med_rt = np.median(rt_arr[l_snr])
                        l_rts = [l_snr & (rt_arr <= med_rt), l_snr & (rt_arr > med_rt)]
                    else:
                        l_rts = [np.zeros_like(l_snr), np.zeros_like(l_snr)]
                    for ri in range(2):
                        bound_summary_[si, bi, ni, ri, :] = _summarize(l_rts[ri])

                else:  # 'all'
                    bound_summary_[si, bi, ni, 0, :] = _summarize(l_snr)

    return bound_summary_


def get_cp_generative_params(data_table, decimals=6):
    """Generative step mean and SD of the CP task's two fixed-SNR blocks, read from the data.

    The single source of truth for the CP task's SNR design: calibration
    notebooks (Make_RRMatrix, Make_biasCorrection Part 2) should simulate at
    these values rather than hardcoding them, and loaders
    (`load_cp_rr_mats`, `get_data_table`'s bias-correction check) verify
    saved calibrations against them.

    Parameters
    ----------
    data_table : pd.DataFrame
        MXSC data table from `get_data_table` (needs block_index, snr,
        step_std). Canonical blocks 1/2 are the fixed low-/high-SNR blocks.
    decimals : int
        Rounding applied before checking that each block has a single value
        (absorbs floating-point noise in the logged step values).

    Returns
    -------
    dict
        {'low': (mean, std), 'high': (mean, std)} per-step generative
        parameters of the low- and high-SNR conditions.

    Raises
    ------
    ValueError
        If either fixed block is missing or has more than one distinct
        (mean, std) pair across subjects -- i.e. the data mix task designs.
    """
    params = {}
    for name, block in (("low", 1), ("high", 2)):
        rows = data_table[data_table["block_index"] == block]
        means = np.unique(np.round((rows["snr"].abs() * rows["step_std"]).dropna(), decimals))
        stds = np.unique(np.round(rows["step_std"].dropna(), decimals))
        if len(means) != 1 or len(stds) != 1:
            raise ValueError(
                f"Block {block} ({name} SNR) has generative means {means.tolist()} and SDs "
                f"{stds.tolist()}; expected exactly one of each (are task designs mixed?)."
            )
        params[name] = (float(means[0]), float(stds[0]))
    return params


def check_calibration_snrs(calibrated_snrs, data_table, source="calibration", atol=1e-3):
    """Raise if any SNR in the data was not simulated by a calibration.

    Parameters
    ----------
    calibrated_snrs : array-like
        SNRs the calibration was simulated at (e.g. the `snrs` field of
        boundBiasCorrection_CP.mat).
    data_table : pd.DataFrame
        Data table with an `snr` column.
    source : str
        Name of the calibration, used in the error message.
    atol : float
        Absolute tolerance for matching a data SNR to a calibrated one.

    Raises
    ------
    ValueError
        If any finite |snr| in the data is farther than `atol` from every
        calibrated SNR.
    """
    calibrated = np.atleast_1d(np.asarray(calibrated_snrs, dtype=float))
    data_snrs = np.unique(np.round(data_table["snr"].abs().dropna(), 6))
    unmatched = [float(s) for s in data_snrs if not np.any(np.abs(calibrated - s) <= atol)]
    if unmatched:
        raise ValueError(
            f"{source} was simulated at SNRs {np.round(calibrated, 4).tolist()}, but the data "
            f"contain SNRs {unmatched} it does not cover. Rebuild it for the current task design."
        )


def load_cp_rr_mats(path, data_table):
    """Load the CP reward-rate matrices, verifying they match the data's task design.

    Parameters
    ----------
    path : str or Path
        RRMats.mat saved by notebooks/Make_RRMatrix.ipynb.
    data_table : pd.DataFrame
        MXSC data table from `get_data_table` (canonical block numbering).

    Returns
    -------
    dict
        The loaded .mat contents (`squeeze_me=True, struct_as_record=False`),
        with `pmats` (LowHigh, HighLow), `bounds`, `cp_steps_lh`,
        `cp_steps_hl`, `g_means`, `g_std`.

    Raises
    ------
    ValueError
        If the matrices were simulated at different generative means/SD than
        the data's fixed blocks, or if any CP step in the data (blocks 3/4)
        is missing from the matrices' CP-step axis.
    """
    rr_mat = scipy.io.loadmat(path, squeeze_me=True, struct_as_record=False)
    gen = get_cp_generative_params(data_table)
    expected_means = [gen["low"][0], gen["high"][0]]
    expected_std = gen["low"][1]
    if gen["high"][1] != expected_std:
        raise ValueError(f"Low/high blocks use different step SDs: {gen}")
    saved_means = np.atleast_1d(rr_mat["g_means"]).astype(float)
    saved_std = float(rr_mat["g_std"])
    if not (np.allclose(saved_means, expected_means) and np.isclose(saved_std, expected_std)):
        raise ValueError(
            f"{path} was simulated with g_means={saved_means.tolist()}, g_std={saved_std}, but the "
            f"data's fixed blocks use means {expected_means}, std {expected_std}. "
            "Rebuild it with notebooks/Make_RRMatrix.ipynb."
        )
    for block, key in ((3, "cp_steps_lh"), (4, "cp_steps_hl")):
        data_steps = np.unique(data_table.loc[data_table["block_index"] == block, "change_point"].dropna())
        missing = np.setdiff1d(data_steps, np.atleast_1d(rr_mat[key]).astype(float))
        if missing.size:
            raise ValueError(f"{path} {key} lacks CP steps present in the data: {missing.astype(int).tolist()}")
    return rr_mat


@dataclass
class BoundSummariesWCPOptions:
    """
    Options for get_bound_summaries_wcp, mirroring the MATLAB getBoundSummarieswCP
    `arguments` block (renamed to snake_case). Only `min_dt` is currently read by
    get_bound_summaries_wcp; the rest are accepted for parity with the MATLAB
    options struct but have no effect yet.

    Parameters
    ----------
    min_n : int
        Minimum number of trials for a subject/condition to be included.
    min_dt : float
        Minimum DT (decision time, steps); applied as `DT >= min_dt`, matching
        get_good_trial_array's standard quality filter. The only field
        get_bound_summaries_wcp currently reads.
    max_dt : int
        Maximum DT (decision time, steps) to include.
    num_sims : int
        Number of simulated repetitions per condition.
    block : int
        Reference block index for the options struct's own default condition.
    show_rr : bool
        Whether to include reward-rate output.
    num_rr_reps : int
        Number of simulated repetitions used for reward-rate estimates.
    scale_coins : bool
        Whether to scale coin counts before reward-rate calculations.
    quartile : int
        Which quartile (1 to 4) of a distribution to use where applicable.
    dt_cutoff : float
        DT (decision time, steps) cutoff used for late-decision comparisons.
    """
    min_n: int = 1
    min_dt: float = 2
    max_dt: int = 50
    num_sims: int = 1
    block: int = 4
    show_rr: bool = True
    num_rr_reps: int = 100
    scale_coins: bool = True
    quartile: int = 1  # 1 to 4
    dt_cutoff: float = 11


def _get_option(options: Any, name: str, default: Any) -> Any:
    """Read an option from either a mapping or an attribute object."""
    if options is None:
        return default
    if isinstance(options, Mapping):
        return options.get(name, default)
    return getattr(options, name, default)


def get_bound_summaries_wcp(data_table_mxsc: pd.DataFrame, options: Any = None) -> dict[str, Any]:
    """Python translation of the MATLAB getBoundSummarieswCP function.

    Parameters
    ----------
    data_table_mxsc : pandas.DataFrame
        Output of ``get_data_table(task_type="MXSC")``. Must contain columns
        subject_index, block_index, DT, RT, correct, change_point.
    options : mapping or object, optional
        Supports the same fields as the MATLAB `arguments` block (renamed to
        snake_case here): min_n, min_dt, max_dt, num_sims, block, show_rr,
        num_rr_reps, scale_coins, quartile, dt_cutoff. Only min_dt is
        currently read by this function; the rest are accepted for parity
        with the MATLAB options struct. min_dt is applied as `DT >= min_dt`,
        matching get_good_trial_array's standard quality filter.

    Returns
    -------
    dict
        A dictionary mirroring the MATLAB `boundSummaries` struct.
    """
    opts = BoundSummariesWCPOptions(
        min_n=_get_option(options, "min_n", BoundSummariesWCPOptions.min_n),
        min_dt=_get_option(options, "min_dt", BoundSummariesWCPOptions.min_dt),
        max_dt=_get_option(options, "max_dt", BoundSummariesWCPOptions.max_dt),
        num_sims=_get_option(options, "num_sims", BoundSummariesWCPOptions.num_sims),
        block=_get_option(options, "block", BoundSummariesWCPOptions.block),
        show_rr=_get_option(options, "show_rr", BoundSummariesWCPOptions.show_rr),
        num_rr_reps=_get_option(options, "num_rr_reps", BoundSummariesWCPOptions.num_rr_reps),
        scale_coins=_get_option(options, "scale_coins", BoundSummariesWCPOptions.scale_coins),
        quartile=_get_option(options, "quartile", BoundSummariesWCPOptions.quartile),
        dt_cutoff=_get_option(options, "dt_cutoff", BoundSummariesWCPOptions.dt_cutoff),
    )

    subject_ids = np.sort(data_table_mxsc["subject_index"].dropna().unique())
    num_subjects = len(subject_ids)

    task_types = ["MX-LH", "MX-HL", "Low", "High"]
    titles = ["LowHigh", "HighLow", "Low", "High"]
    # Canonical block numbering (see get_data_table's block_index remapping):
    # 1/2 = fixed-low/fixed-high, 3/4 = LowHigh/HighLow change-point blocks.
    blocks = [3, 4, 1, 2]
    cond_dict = dict(zip(task_types, blocks))

    bound_summaries: dict[str, Any] = {}

    # main results
    for tt in range(2):
        # Collect data
        cond_block = cond_dict[task_types[tt]]
        lb  = data_table_mxsc["block_index"] == cond_block
        # Standard DT >= min_dt quality filter (matches get_good_trial_array),
        # removing short DTs that are difficult to estimate bounds from.
        ldt = data_table_mxsc["DT"] >= opts.min_dt
        cond_table = data_table_mxsc.loc[lb & ldt].reset_index(drop=True)

        fixed_block = cond_dict[task_types[tt + 2]]
        lf = data_table_mxsc["block_index"] == fixed_block
        fixed_table = data_table_mxsc.loc[lf & ldt].reset_index(drop=True)

        # Bound summary, collapsed across all RTs. get_bound_summary splits
        # change-point blocks on pre-/post-changepoint (RT vs change_point)
        # rather than literal |snr|, giving exactly 2 columns per subject:
        # [0] = pre-change bound, [1] = post-change bound.
        # subject_indices=subject_ids pins every call to the same full
        # subject list (NaN row for any subject missing this block) so
        # LowHigh/HighLow/Low/High/CPLowHigh/CPHighLow all stay row-aligned
        # to the same subject -- without it, each call derives its own
        # subject axis from whichever subjects happen to have data in that
        # particular block, which can differ in count and order across
        # blocks (e.g. not every subject has usable block-5 data).
        bound_summary = get_bound_summary(
            cond_table,
            blocks=cond_block,
            max_rt="all",
            subject_indices=subject_ids,
        )
        bound_summary = np.asarray(bound_summary)
        bound_summaries[titles[tt]] = bound_summary[:, 0, :, 0, 0]
        # SEM = std / sqrt(n); not part of the original MATLAB struct, but
        # std (index 1) and n (index 2) are already computed by
        # get_bound_summary, so this is free to add alongside the mean.
        bound_summaries[f"SEM{titles[tt]}"] = (
            bound_summary[:, 0, :, 0, 1] / np.sqrt(bound_summary[:, 0, :, 0, 2])
        )

        # split_by_snr=False: each subject has exactly one |snr| in a fixed
        # block (their own staircase-calibrated level), so splitting by |snr|
        # would fragment subjects across columns instead of summarizing them
        # together.
        bound_summary_fixed = get_bound_summary(
            fixed_table,
            blocks=fixed_block,
            max_rt="medsplit",
            split_by_snr=False,
            subject_indices=subject_ids,
        )
        bound_summary_fixed = np.asarray(bound_summary_fixed)
        bound_summaries[titles[tt + 2]] = bound_summary_fixed[:, 0, 0, :, 0]
        bound_summaries[f"SEM{titles[tt + 2]}"] = (
            bound_summary_fixed[:, 0, 0, :, 1] / np.sqrt(bound_summary_fixed[:, 0, 0, :, 2])
        )

        dt_summary = np.full((num_subjects, 3), np.nan, dtype=float)
        acc_summary = np.full((num_subjects, 2), np.nan, dtype=float)

        for ii, ss in enumerate(subject_ids):
            ls = cond_table["subject_index"] == ss
            lsf = (fixed_table["subject_index"] == ss if ls.any()
                   else pd.Series(False, index=fixed_table.index))

            dt_summary[ii, 0] = np.nanmedian(fixed_table.loc[lsf, "DT"]) if lsf.any() else np.nan
            dt_summary[ii, 1] = np.nanmedian(cond_table.loc[ls, "DT"]) if ls.any() else np.nan

            cp_values = pd.unique(cond_table.loc[ls, "change_point"].dropna())
            if len(cp_values) == 1:
                dt_summary[ii, 2] = float(cp_values[0])
            elif len(cp_values) > 1:
                raise ValueError(
                    f"Expected a single change_point for subject {ss}, block {cond_block}; "
                    f"got {cp_values}."
                )

            acc_summary[ii, 0] = np.nanmean(fixed_table.loc[lsf, "correct"]) if lsf.any() else np.nan
            acc_summary[ii, 1] = np.nanmean(cond_table.loc[ls, "correct"]) if ls.any() else np.nan

        bound_summaries[f"CP{titles[tt]}"] = dt_summary[:, 2]

    return bound_summaries
